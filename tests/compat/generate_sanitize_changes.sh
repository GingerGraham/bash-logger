#!/usr/bin/env bash
#
# generate_sanitize_changes.sh - Record the sanitizing results that changed in 3.0
#
# Usage: tests/compat/generate_sanitize_changes.sh <2.7.0 logging.sh> <logging.sh>
#
# Writes tests/compat/golden/sanitize_3.0.tsv: every row of sanitize.tsv whose result
# differs in the given logging.sh, with its new checksum and the reason it changed.
# test_sanitize_equivalence.sh applies these rows on top of sanitize.tsv, which stays the
# record of 2.7.0.
#
# 3.0 removes more from messages than 2.7.0 did (security review of 3.0.0, findings P1 and
# P2). Each changed row must have at least one of these reasons, or the script fails:
#   esc    the 2.7.0 result still contained an escape character, which a terminal could act on
#   utf8   the 2.7.0 result was not valid UTF-8: it removed ESC with the first byte of the
#          UTF-8 character after it
#   c1     the message contains a C1 control character (U+0080 to U+009F), now removed
# The new result must not contain an escape character.
#
# Run it with bash and LC_ALL=C, as generate_sanitize_golden.sh was.

set -euo pipefail

if [[ $# -ne 2 || ! -f "$1" || ! -f "$2" ]]; then
    echo "Usage: $0 <2.7.0 logging.sh> <logging.sh>" >&2
    exit 1
fi

baseline_script="$(cd "$(dirname "$1")" && pwd)/$(basename "$1")"
candidate_script="$(cd "$(dirname "$2")" && pwd)/$(basename "$2")"
compat_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
golden_dir="$compat_dir/golden"
corpus_file="$golden_dir/sanitize_corpus.txt"

work_dir=$(mktemp -d)
trap 'rm -rf "$work_dir"' EXIT

export LC_ALL=C

# Log every corpus message in the three modes and keep each log file, as
# sanitize_driver.sh does before it checksums them
write_rows() {
    local logging_script="$1"
    local rows_dir="$2"
    mkdir -p "$rows_dir"
    bash -c '
        logging_script="$1"
        corpus_file="$2"
        rows_dir="$3"
        . "$logging_script"
        init_logger --quiet --no-color --no-init-message --format "%m" --max-line-length 0 \
            --log "$rows_dir/init.log" || exit 1
        tab=$(printf "\t")
        while IFS="$tab" read -r message_id encoded_message || [ -n "$message_id" ]; do
            case "$message_id" in
                ""|"#"*) continue ;;
            esac
            message=$(printf "${encoded_message}x")
            message="${message%x}"
            for mode in default allow_newlines allow_ansi; do
                LOG_UNSAFE_ALLOW_NEWLINES="false"
                LOG_UNSAFE_ALLOW_ANSI_CODES="false"
                case "$mode" in
                    allow_newlines) LOG_UNSAFE_ALLOW_NEWLINES="true" ;;
                    allow_ansi) LOG_UNSAFE_ALLOW_ANSI_CODES="true" ;;
                esac
                LOG_FILE="$rows_dir/$mode.$message_id"
                : > "$LOG_FILE"
                log_info "$message"
            done
        done < "$corpus_file"
    ' bash "$logging_script" "$corpus_file" "$rows_dir" 2>/dev/null
}

write_rows "$baseline_script" "$work_dir/baseline"
write_rows "$candidate_script" "$work_dir/candidate"

escape_character=$(printf '\033')
c1_pattern=$(printf '\302[\200-\237]')

{
    printf '# Sanitizing results that changed in 3.0, applied on top of sanitize.tsv.\n'
    printf '# Generated by tests/compat/generate_sanitize_changes.sh; do not edit by hand.\n'
    printf '# Columns: mode, corpus id, checksum, reasons (see the generator for each reason).\n'
    changed_count=0
    while IFS=$'\t' read -r mode message_id _; do
        [[ -z "$mode" || "$mode" == '#'* ]] && continue
        baseline_row="$work_dir/baseline/$mode.$message_id"
        candidate_row="$work_dir/candidate/$mode.$message_id"
        if cmp -s "$baseline_row" "$candidate_row"; then
            continue
        fi
        if grep -q "$escape_character" "$candidate_row"; then
            echo "Error: $mode $message_id still contains an escape character" >&2
            exit 1
        fi
        reasons=""
        if grep -q "$escape_character" "$baseline_row"; then
            reasons="${reasons},esc"
        fi
        if ! iconv -f UTF-8 -t UTF-8 "$baseline_row" >/dev/null 2>&1 \
            && iconv -f UTF-8 -t UTF-8 "$candidate_row" >/dev/null 2>&1; then
            reasons="${reasons},utf8"
        fi
        if grep -q "$c1_pattern" "$baseline_row"; then
            reasons="${reasons},c1"
        fi
        if [[ -z "$reasons" ]]; then
            echo "Error: $mode $message_id changed for no listed reason" >&2
            exit 1
        fi
        checksum=$(cksum < "$candidate_row")
        printf '%s\t%s\t%s\t%s\n' "$mode" "$message_id" "${checksum%% *}" "${reasons#,}"
        changed_count=$((changed_count + 1))
    done < <(grep -v '^#' "$golden_dir/sanitize.tsv")
    echo "Changed rows: $changed_count" >&2
} > "$golden_dir/sanitize_3.0.tsv"

echo "Wrote $golden_dir/sanitize_3.0.tsv" >&2
